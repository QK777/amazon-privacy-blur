  '#address-ui-widgets-AddressLine1', '#address-ui-widgets-AddressLine2',
  '#address-ui-widgets-CityStatePostalCode', '#address-ui-widgets-Country',
  '#address-ui-widgets-PhoneNumber', '[id^="ya-myab-display-address-block-"]',
  '.recipient', '.yohtmlc-recipient',
  '.displayAddressDiv', '.displayAddressUL', '.displayAddressFullName',
  '.displayAddressAddressLine1', '.displayAddressAddressLine2', '.displayAddressAddressLine3',
  '.displayAddressCityStateOrRegionPostalCode', '.displayAddressCountryName', '.displayAddressPhoneNumber',
