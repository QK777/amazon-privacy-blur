function generateCSS() {
  const scope = 'html:not([data-apb-off])';
  const fields = `:is(\n  ${textFields.join(',\n  ')}\n)`;
  const nativeFields = `:is(input, textarea, select):is(\n  ${inputFields.join(',\n  ')}\n)`;
  const pattern = 'url("data:image/png;base64,' + starPattern() + '")';
  const starScope = scope + ':not([data-apb-mode="blur"])';
  return `/* Generated by node scripts/generate-css.cjs. Original form values stay unchanged. */
/* Inline wrappers are used only for partial postal/optional-text matches. */
[data-apb-mask] {
  display: inline !important;
  font-size: inherit !important;
  line-height: inherit !important;
  margin: 0 !important;
  padding: 0 !important;
  border: 0 !important;
  font-family: inherit !important;
  font-weight: inherit !important;
  font-style: inherit !important;
  font-variant: inherit !important;
  font-feature-settings: inherit !important;
  letter-spacing: inherit !important;
  word-spacing: inherit !important;
}

::highlight(apb-private-text) {
  color: transparent;
  text-shadow: 0 0 7px #555;
}

/* Automatic fields: apply from document_start, before any JS scan or name registration.
   Descendants may override Amazon's text color; mask those too without filtering boxes. */
${scope} [data-apb-mask],
${scope} ${fields},
${scope} ${fields} * {
  color: transparent !important;
  -webkit-text-fill-color: transparent !important;
  text-shadow: 0 0 7px #555 !important;
  text-decoration-color: transparent !important;
}

/* Native form values cannot be targeted by the Highlight API. */
${scope} ${nativeFields} {
  color: transparent !important;
  -webkit-text-fill-color: transparent !important;
  text-shadow: 0 0 7px #555 !important;
}

/* Stars are paint only. Keep the original fonts, advances, line boxes and icons. */
${starScope} [data-apb-mask],
${starScope} ${fields},
${starScope} ${fields} *,
${starScope} ${nativeFields} {
  text-shadow: none !important;
}

/* Paint only the outermost field to avoid overlapping patterns on nested address lines. */
${starScope} [data-apb-mask],
${starScope} ${fields}:not(${fields} *),
${starScope} ${fields} :is(input, textarea, select),
${starScope} ${nativeFields} {
  background-image: ${pattern} !important;
  background-repeat: repeat !important;
  background-size: .75em 1lh !important;
  background-position: left top !important;
}
`;
}
