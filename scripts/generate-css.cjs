function starPattern() {
  const width=12,height=24,rows=Buffer.alloc((width*4+1)*height);
  for(let y=0;y<height;y++)for(let x=0;x<width;x++){
    let covered=0;
    for(let sy=0;sy<4;sy++)for(let sx=0;sx<4;sx++){
      const px=x+(sx+.5)/4-6,py=y+(sy+.5)/4-12;
      if([Math.PI/2,Math.PI/6,-Math.PI/6].some(angle=>{
        const along=px*Math.cos(angle)+py*Math.sin(angle);
        const across=-px*Math.sin(angle)+py*Math.cos(angle);
        return Math.abs(along)<=4.8&&Math.abs(across)<=.65;
      }))covered++;
    }
    const offset=y*(width*4+1)+1+x*4;
    rows[offset]=rows[offset+1]=rows[offset+2]=85;rows[offset+3]=Math.round(covered*255/16);
  }
  const crc=data=>{let value=0xffffffff;for(const byte of data){value^=byte;for(let i=0;i<8;i++)value=(value>>>1)^((value&1)?0xedb88320:0);}return(value^0xffffffff)>>>0;};
  const chunk=(type,data)=>{const name=Buffer.from(type),size=Buffer.alloc(4),check=Buffer.alloc(4);
    size.writeUInt32BE(data.length);check.writeUInt32BE(crc(Buffer.concat([name,data])));return Buffer.concat([size,name,data,check]);};
  const header=Buffer.alloc(13);header.writeUInt32BE(width);header.writeUInt32BE(height,4);header[8]=8;header[9]=6;
  return Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]),chunk('IHDR',header),chunk('IDAT',deflateSync(rows)),chunk('IEND',Buffer.alloc(0))]).toString('base64');
}
